"""Generate the two-cell standalone notebook from readable repository sources."""
from pathlib import Path
import base64
import hashlib
import io
import json
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def payload():
    paths = sorted((ROOT/'src/breezesprint25').glob('*.py'))
    paths += [ROOT/'src/breezesprint25/model.json', ROOT/'requirements-tpu.lock']
    bio = io.BytesIO()
    with zipfile.ZipFile(bio, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for path in paths:
            info = zipfile.ZipInfo(path.relative_to(ROOT).as_posix(), date_time=(2026,9,21,0,0,0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, path.read_bytes())
    data = bio.getvalue()
    return data, [p.relative_to(ROOT).as_posix() for p in paths]


